    private void restartAppAfterConfigChanged() {
        Toast.makeText(mContext, "配置已切换,即将重新加载!", Toast.LENGTH_SHORT).show();
        clearConfigSwitchCache();
        new Handler().postDelayed(new Runnable() {
            @Override
            public void run() {
                if (mActivity != null && !mActivity.isFinishing()) {
                    mActivity.onBackPressed();
                }
            }
        }, 2500);
    }

    private void clearConfigSwitchCache() {
        try {
            SourceViewModel.clearRuntimeCache();
//            FileUtils.clearSpiderCacheFiles();
            LOG.i("echo-clear-config-switch-cache");
        } catch (Exception e) {
            LOG.i("echo-clear-config-switch-cache-error:" + e.getMessage());
            e.printStackTrace();
        }
    }

    private void restartAppAfterCacheCleared() {
        Toast.makeText(mContext, "缓存已清空,即将回到主页!", Toast.LENGTH_LONG).show();
        new Handler().postDelayed(new Runnable() {
            @Override
            public void run() {
                restartApp();
            }
        }, 2500);
    }

    /** 配置名显示：url → 名称（ConfigRepo 持久映射 + 配置列表匹配，空 → "未配置"，找不到显示 url 本身）。 */
    private String moduleConfigDisplay(String url) {
        return com.github.gcd888.guoju.api.ConfigRepo.displayNameFor(url);
    }

    /** 刷新四模块地址入口的当前配置名显示。 */
    private void refreshModuleAddrTexts() {
        if (tvApi != null) tvApi.setText(moduleConfigDisplay(Hawk.get(HawkConfig.API_URL, "")));
        if (tvLiveAddr != null) tvLiveAddr.setText(moduleConfigDisplay(Hawk.get(HawkConfig.LIVE_API_URL, "")));
        if (tvDramaAddr != null) tvDramaAddr.setText(moduleConfigDisplay(Hawk.get(HawkConfig.DRAMA_CONFIG_URL, "")));
        if (tvMusicAddr != null) tvMusicAddr.setText(moduleConfigDisplay(Hawk.get(HawkConfig.MUSIC_CONFIG_URL, "")));
    }

    /** 弹统一配置弹窗（PRD 4.3），定位到指定模块当前配置项并默认选中对应类别 Tab。 */
    private void showConfigDialog(String locateUrl, int moduleType) {
        ConfigDialog dialog = new ConfigDialog(mActivity, locateUrl == null ? "" : locateUrl, moduleType);
        dialog.setOnDismissListener(new DialogInterface.OnDismissListener() {
            @Override
            public void onDismiss(DialogInterface dialog) {
                ((BaseActivity) mActivity).hideSysBar();
                // 切配置走全量重载（ConfigDialog.applyLine 重建 HomeActivity），返回时刷新地址显示即可
                refreshModuleAddrTexts();
            }
        });
        dialog.show();
    }

    private void refreshDanmuApiText() {
        if (tvDanmuApiText == null) return;
        if (DanmakuApi.isUseDefault()) {
            tvDanmuApiText.setText("默认");
            return;
        }
        String custom = Hawk.get(HawkConfig.DANMU_API, "");
        if (!custom.isEmpty()) {
            tvDanmuApiText.setText("自定义");
            return;
        }
        String config = ApiConfig.get().getDanmaku();
        tvDanmuApiText.setText(config.isEmpty() ? "默认" : "接口");
    }

    private void restartApp() {
        if (mContext == null) return;
        Intent intent = mContext.getPackageManager().getLaunchIntentForPackage(mContext.getPackageName());
        if (intent != null) {
            intent.addFlags(Intent.FLAG_ACTIVITY_CLEAR_TOP);
            startActivity(intent);
            System.exit(0);
        }
    }

    private void onClickIjkCachePlay(View v) {
        FastClickCheckUtil.check(v);
        Hawk.put(HawkConfig.IJK_CACHE_PLAY, !Hawk.get(HawkConfig.IJK_CACHE_PLAY, false));
        tvIjkCachePlay.setText(Hawk.get(HawkConfig.IJK_CACHE_PLAY, false) ? "开启" : "关闭");
    }

    private void onClickClearCache(View v) {
        FastClickCheckUtil.check(v);
        String cachePath = FileUtils.getCachePath();
        File cacheDir = new File(cachePath);
        new Thread(() -> {
            try {
                ApiConfig.get().clearSpiderCache();
                if(cacheDir.exists())FileUtils.cleanDirectory(cacheDir);
                FileUtils.clearSpiderCacheFiles();
            } catch (Exception e) {
                e.printStackTrace();
            } finally {
                if (mActivity != null) {
                    mActivity.runOnUiThread(new Runnable() {
                        @Override
                        public void run() {
                            restartAppAfterCacheCleared();
                        }
                    });
                }
            }
        }).start();
    }

